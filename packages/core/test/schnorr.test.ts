for (const vector of SIGNING_VECTORS) {
  test(`BIP340 vector ${vector.index}: derives the public key`, () => {
    expect(bytesToHex(publicKey(hexToBytes(vector.secret))).toUpperCase()).toBe(vector.pubkey);
  });

  test(`BIP340 vector ${vector.index}: produces the reference signature`, () => {
    const signature = sign(hexToBytes(vector.message), hexToBytes(vector.secret), hexToBytes(vector.aux));
    expect(bytesToHex(signature).toUpperCase()).toBe(vector.signature);
  });

  test(`BIP340 vector ${vector.index}: verifies`, () => {
    expect(verify(hexToBytes(vector.signature), hexToBytes(vector.message), hexToBytes(vector.pubkey))).toBe(true);
  });
}

